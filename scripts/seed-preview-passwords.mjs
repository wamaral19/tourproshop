#!/usr/bin/env node
/**
 * Turns a CSV of preview passwords into SQL for the `preview_passwords` table.
 *
 *     node scripts/seed-preview-passwords.mjs preview-passwords.csv
 *
 * Two shapes are accepted:
 *
 *   email@agency.com                 one column — the address is the password,
 *                                    and is also what the dashboard shows
 *   email@agency.com,swift-heron-41  two columns — a code they were sent, with
 *                                    the email kept as the label
 *
 * The one-column form is what we run today: each agent's own address is their
 * password, so there is nothing to distribute and the log names whoever looked.
 * The two-column form is there for when someone needs a code instead — the row
 * keeps naming them without the code being readable back out.
 *
 * Passwords are hashed here and never written to the SQL. In the one-column
 * form the address goes in as the label too, so it *is* recoverable — that is
 * the deal with using emails as passwords, and it's why the addresses are only
 * as private as the D1 they already sit in.
 *
 * Row order becomes `password_index`, which is stable across re-runs: the
 * insert upserts on it, so a corrected CSV replaces hashes without disturbing
 * the log or the use counts. Keep the row order stable if you edit the file.
 *
 * Writes preview-passwords.generated.sql and prints the command to apply it. It
 * does not touch the database itself.
 */
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const OUT = path.join(ROOT, "preview-passwords.generated.sql");

/** Must match `normalizePassword` in worker-gate.js exactly. */
function normalizePassword(password) {
  return password.trim().toLowerCase();
}

function sha256Hex(input) {
  return createHash("sha256").update(input, "utf8").digest("hex");
}

function sqlString(value) {
  return value === null ? "NULL" : `'${value.replace(/'/g, "''")}'`;
}

const EMAIL_RE = /^[^\s@,]+@[^\s@,]+\.[a-z]{2,}$/i;

const input = process.argv[2];
if (!input) {
  console.error(
    "Usage: node scripts/seed-preview-passwords.mjs <path-to-csv>\n\n" +
      "One password per line, or `email,password` per line.",
  );
  process.exit(1);
}
if (!fs.existsSync(input)) {
  console.error(`No such file: ${input}`);
  process.exit(1);
}

const lines = fs
  .readFileSync(input, "utf8")
  .split(/\r?\n/)
  .map((line) => line.trim().replace(/,+$/, ""))
  .filter(Boolean);

if (lines.length === 0) {
  console.error("That CSV has no rows in it.");
  process.exit(1);
}

// A header row is a first line that reads like column names rather than data.
const HEADERISH = /^(email|e-?mail|address|password|code|passcode)\b/i;
const dataLines = HEADERISH.test(lines[0]) && !EMAIL_RE.test(lines[0])
  ? lines.slice(1)
  : lines;

if (dataLines.length === 0) {
  console.error("That CSV has a header but no rows under it.");
  process.exit(1);
}

/** @type {{ email: string | null, password: string }[]} */
const entries = [];
for (const [i, line] of dataLines.entries()) {
  const cells = line.split(",").map((c) => c.trim().replace(/^"(.*)"$/, "$1"));
  if (cells.length === 1) {
    const value = cells[0];
    // A lone address is both the password and the label. A lone anything-else
    // is a password with nobody's name on it.
    entries.push({
      email: EMAIL_RE.test(value) ? normalizePassword(value) : null,
      password: value,
    });
  } else if (cells.length === 2) {
    entries.push({ email: normalizePassword(cells[0]), password: cells[1] });
  } else {
    console.error(
      `Row ${i + 1} has ${cells.length} columns. Expected one (password) or ` +
        "two (email,password).",
    );
    process.exit(1);
  }
}

// Passwords are matched case-insensitively so they survive being typed by hand.
// Two that collide under that would be one password, which is a real problem in
// the CSV rather than something to paper over here.
const seen = new Map();
const collisions = [];
entries.forEach((entry, i) => {
  const normalized = normalizePassword(entry.password);
  if (seen.has(normalized)) {
    collisions.push(`  row ${seen.get(normalized) + 1} and row ${i + 1}`);
  } else {
    seen.set(normalized, i);
  }
});
if (collisions.length > 0) {
  console.error(
    "These rows hold the same password once case and whitespace are ignored,\n" +
      "and passwords are matched that way because people type them by hand:\n\n" +
      collisions.join("\n") +
      "\n\nMake them distinct and re-run.",
  );
  process.exit(1);
}

const values = entries
  .map(
    (entry, i) =>
      `  (${i + 1}, '${sha256Hex(normalizePassword(entry.password))}', ${sqlString(entry.email)})`,
  )
  .join(",\n");

const named = entries.filter((e) => e.email).length;

const sql = `-- Generated by scripts/seed-preview-passwords.mjs from ${path.basename(input)}
-- ${entries.length} preview passwords, ${named} of them attributed to an email.
--
-- Apply locally:  npx wrangler d1 execute tourproshop-outreach --local  --file=preview-passwords.generated.sql
-- Apply remote:   npx wrangler d1 execute tourproshop-outreach --remote --file=preview-passwords.generated.sql

INSERT INTO preview_passwords (password_index, password_hash, email) VALUES
${values}
ON CONFLICT(password_index) DO UPDATE SET
  password_hash = excluded.password_hash,
  email         = excluded.email,
  revoked_at    = NULL;
`;

fs.writeFileSync(OUT, sql);

const domains = new Set(
  entries.filter((e) => e.email).map((e) => e.email.split("@")[1]),
);

console.log(
  `Wrote ${entries.length} passwords → preview-passwords.generated.sql\n` +
    `  ${named} attributed to an email, across ${domains.size} domains\n\n` +
    "Apply them with:\n\n" +
    "  npx wrangler d1 execute tourproshop-outreach --remote --file=preview-passwords.generated.sql\n",
);
