#!/usr/bin/env node
/**
 * Writes lib/site-mode.generated.ts — the three flags that decide which of the
 * two builds this is.
 *
 * Why generate a file instead of reading `process.env` from lib/site-mode.ts:
 * the flags have to be *literals in the source* by the time Next compiles.
 *
 *   - A `process.env` read survives into the server bundle and is resolved at
 *     runtime off the Worker env, so the flag would have to be kept in sync in
 *     two places (the build environment and `vars` in wrangler.jsonc). A
 *     mismatch means the server renders one site and the client hydrates the
 *     other.
 *   - Literals fold. `LOCKDOWN = true` lets the bundler drop the branches it
 *     guards, so the locked build ships less of the storefront rather than
 *     shipping it all behind an `if`.
 *
 * Runs first in `npm run build`, ahead of every other generator, because the
 * neutral-media pass keys off the same flags.
 */
import fs from "node:fs";
import path from "node:path";
import { resolveSiteMode } from "./site-mode.mjs";

const ROOT = process.cwd();
const OUT = path.join(ROOT, "lib", "site-mode.generated.ts");

const { mode, lockdown, hidePlayerNames, preview } = resolveSiteMode();

// `: boolean` rather than a literal type on purpose — the emitted JS is still a
// constant the bundler can fold, but TypeScript won't narrow every consumer to
// a dead branch and start reporting unreachable code in whichever build has the
// flag off.
const contents = `// Generated by scripts/generate-site-mode.mjs — do not edit.
// Built as: SITE_MODE=${mode}
// Read these through lib/site-mode.ts, which derives the flags the app uses.

export const LOCKDOWN: boolean = ${lockdown};
export const HIDE_PLAYER_NAMES: boolean = ${hidePlayerNames};
export const SITE_PREVIEW: boolean = ${preview};
`;

const existing = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : null;
if (existing !== contents) fs.writeFileSync(OUT, contents);

console.log(
  `Site mode: ${mode}` +
    (hidePlayerNames ? ", player names hidden" : ", player names shown") +
    (preview ? ", password-gated preview build" : ""),
);
