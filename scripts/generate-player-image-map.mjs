import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, "..");
const SRC = path.join(ROOT, "public", "player images");
const OUT = path.join(ROOT, "lib", "player-image-map.generated.ts");

function slugify(input) {
  return input
    .toLowerCase()
    .normalize("NFD")
    .replace(/\p{Diacritic}/gu, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

const map = {};
for (const file of fs.readdirSync(SRC)) {
  if (file.startsWith(".")) continue;
  const base = file.replace(/\.[^.]+$/, "");
  const slug = slugify(base);
  map[slug] = `/${encodeURIComponent("player images")}/${encodeURIComponent(file)}`;
}

const body = `// Generated by scripts/generate-player-image-map.mjs — do not edit by hand.
export const PLAYER_IMAGE_MAP: Record<string, string> = ${JSON.stringify(map, null, 2)};
`;

fs.writeFileSync(OUT, body);
console.log(`Wrote ${Object.keys(map).length} entries → ${path.relative(ROOT, OUT)}`);
