#!/usr/bin/env node
/**
 * Publishes name-free copies of the product photography.
 *
 * Hiding player names from copy and alt text isn't enough on its own: the asset
 * paths spell the names out too ("/product images/Sam Burns Polo/..."), and
 * those land in the page source of every live page as `src` and `<link
 * rel=preload>` attributes. Anyone opening DevTools reads the roster.
 *
 * So when PLAYER_NAMES_HIDDEN is on, every photo still referenced by a page is
 * also published under /media/<hash><ext>, and lib/media.ts swaps the paths at
 * render time. On the text-only build that is just the /sponsors charts.
 * The hash is derived from the original path, so URLs are stable across builds
 * and stay cacheable.
 *
 * Runs from `npm run build`. With names not hidden it writes an empty map and
 * clears the directory, so nothing is duplicated when it isn't needed.
 */
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { withheldMedia } from "./dark-media.mjs";
import { resolveSiteMode } from "./site-mode.mjs";

const ROOT = process.cwd();
const OUT_MAP = path.join(ROOT, "lib", "media-map.generated.ts");
const OUT_DIR = path.join(ROOT, "public", "media");

/** Files whose `src:` literals we publish neutral copies of. */
const SOURCE_FILES = [
  "lib/products.ts",
  "lib/marketing-assets.ts",
  "app/sponsors/page.tsx",
];

/**
 * The same list for a build with `PHOTOGRAPHY_HIDDEN` on.
 *
 * That build renders no photography, so the search-interest charts on
 * /sponsors are the only `src:` literals that still reach a page. Publishing
 * the rest would copy the whole photography library into the assets the public
 * worker uploads, under opaque URLs that nothing links to — the neutral copy
 * exists to keep a name out of the markup, and there is no markup left to keep
 * it out of.
 *
 * Anything dropped here is still on disk under public/ and still served by the
 * password-gated worker, which builds with photography on. See
 * docs/going-dark.md § "A text-only public build".
 */
const TEXT_ONLY_SOURCE_FILES = ["app/sponsors/page.tsx"];

function namesHidden() {
  return resolveSiteMode().hidePlayerNames;
}

/** Mirrors `PHOTOGRAPHY_HIDDEN` in lib/site-mode.ts — lockdown, and only it. */
function photographyHidden() {
  return resolveSiteMode().lockdown;
}

function collectSources() {
  const found = new Set();
  for (const file of photographyHidden() ? TEXT_ONLY_SOURCE_FILES : SOURCE_FILES) {
    const text = fs.readFileSync(path.join(ROOT, file), "utf8");
    for (const m of text.matchAll(/src: "(\/[^"]+)"/g)) found.add(m[1]);
  }
  // Files withheld from this build render nowhere, so publishing a neutral copy
  // would only republish them under a URL nothing links to.
  const withheld = withheldMedia(ROOT);
  // Placeholders are generated SVG, not photography — nothing to hide.
  return [...found].filter(
    (src) => !src.startsWith("/placeholders/") && !withheld.has(src),
  );
}

function neutralName(src) {
  const hash = createHash("sha1").update(src).digest("hex").slice(0, 16);
  return `${hash}${path.extname(src)}`;
}

function writeMap(map) {
  fs.writeFileSync(
    OUT_MAP,
    `// Generated by scripts/generate-neutral-media.mjs — do not edit by hand.\n` +
      `export const NEUTRAL_MEDIA_MAP: Record<string, string> = ${JSON.stringify(map, null, 2)};\n`,
  );
}

if (!namesHidden()) {
  fs.rmSync(OUT_DIR, { recursive: true, force: true });
  writeMap({});
  console.log("Player names are not hidden — no neutral media published.");
  process.exit(0);
}

fs.rmSync(OUT_DIR, { recursive: true, force: true });
fs.mkdirSync(OUT_DIR, { recursive: true });

const map = {};
const missing = [];
for (const src of collectSources()) {
  const from = path.join(ROOT, "public", decodeURIComponent(src));
  if (!fs.existsSync(from)) {
    missing.push(src);
    continue;
  }
  const name = neutralName(src);
  fs.copyFileSync(from, path.join(OUT_DIR, name));
  map[src] = `/media/${name}`;
}

writeMap(map);
console.log(
  `Published ${Object.keys(map).length} neutral copies → public/media/`,
);
if (missing.length > 0) {
  console.warn(
    `  ${missing.length} referenced file(s) missing on disk, left unmapped:`,
  );
  for (const src of missing) console.warn(`    ${src}`);
}
