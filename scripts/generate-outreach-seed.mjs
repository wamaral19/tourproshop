#!/usr/bin/env node
// Regenerates migrations/0002_outreach_seed.sql from data/outreach.csv.
// Run with: node scripts/generate-outreach-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const csvPath = resolve(root, "data/outreach.csv");
const outPath = resolve(root, "migrations/0002_outreach_seed.sql");

function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let inQuotes = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQuotes) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') { inQuotes = false; }
      else { field += c; }
    } else {
      if (c === '"') { inQuotes = true; }
      else if (c === ",") { row.push(field); field = ""; }
      else if (c === "\n") { row.push(field); rows.push(row); row = []; field = ""; }
      else if (c === "\r") { /* skip */ }
      else { field += c; }
    }
  }
  if (field.length || row.length) { row.push(field); rows.push(row); }
  return rows;
}

function slugify(s) {
  return s
    .toLowerCase()
    .normalize("NFD").replace(/[̀-ͯ]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function sqlEscape(v) {
  if (v == null || v === "") return "NULL";
  return "'" + String(v).replace(/'/g, "''") + "'";
}

const rows = parseCsv(readFileSync(csvPath, "utf8"));
const [header, ...data] = rows;
const idx = Object.fromEntries(header.map((h, i) => [h.trim(), i]));

const seen = new Set();
const inserts = [];
for (const r of data) {
  if (!r || !r[idx.agent_manager]) continue;
  const agent = r[idx.agent_manager].trim();
  if (!agent) continue;
  const slug = slugify(agent);
  if (seen.has(slug)) continue;
  seen.add(slug);
  const agency = r[idx.agency]?.trim() || "";
  const email = r[idx.email]?.trim() || "";
  inserts.push(
    `INSERT OR IGNORE INTO outreach_links (slug, agent_name, agency, email, target_url) VALUES (${sqlEscape(slug)}, ${sqlEscape(agent)}, ${sqlEscape(agency)}, ${sqlEscape(email)}, '/agents');`,
  );
}

const out = [
  "-- Generated by scripts/generate-outreach-seed.mjs. Do not edit by hand.",
  "-- Apply: npx wrangler d1 execute tourproshop-outreach --remote --file=migrations/0002_outreach_seed.sql",
  "",
  ...inserts,
  "",
].join("\n");

writeFileSync(outPath, out);
console.log(`Wrote ${inserts.length} seed rows to ${outPath}`);
